package edu.ai.lms.core.coderunner.app.service;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import edu.ai.lms.core.coderunner.app.domain.ExecutableAssessmentContract;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

@Component
@RequiredArgsConstructor
public class CppCodeRunnerHarnessBuilder {

    private static final int MAX_SOURCE_BYTES = 256_000;

    private final ObjectMapper objectMapper;

    public String buildCase(
            ExecutableAssessmentContract contract,
            String submittedFunction,
            ExecutableAssessmentContract.TestCase testCase) {
        validateSource(contract, submittedFunction);
        if (!"exact_typed".equals(contract.runtime().comparator().id())) {
            throw new IllegalArgumentException("Only exact_typed comparator is supported");
        }

        List<String> arguments = new ArrayList<>();
        for (var argument : contract.runtime().signature().arguments()) {
            JsonNode value = testCase.arguments().get(argument.name());
            if (value == null) {
                throw new IllegalArgumentException("Missing fixture argument: " + argument.name());
            }
            arguments.add(literal(argument.fixture().id(), value));
        }
        String returnType = cppType(contract.runtime().signature().returnFixture().id());
        String argumentTypes = contract.runtime().signature().arguments().stream()
                .map(argument -> cppType(argument.fixture().id()))
                .collect(Collectors.joining(", "));
        List<String> output = outputLines(
                contract.runtime().signature().returnFixture().id(),
                "__lms_actual");

        List<String> lines = new ArrayList<>(List.of(
                "// Generated by LMS Executable Assessment Contract 2.0.0.",
                "#include <algorithm>",
                "#include <iostream>",
                "#include <string>",
                "#include <type_traits>",
                "#include <vector>",
                "",
                submittedFunction.strip(),
                "",
                "#ifdef " + contract.runtime().entryPoint(),
                "#undef " + contract.runtime().entryPoint(),
                "#endif",
                "int main() {",
                "    using __LmsExpectedFunction = " + returnType + " (*)(" + argumentTypes + ");",
                "    static_assert(std::is_same<decltype(&" + contract.runtime().entryPoint()
                        + "), __LmsExpectedFunction>::value, \"Submitted function signature does not match the contract\");",
                "    const " + returnType + " __lms_actual = " + contract.runtime().entryPoint()
                        + "(" + String.join(", ", arguments) + ");",
                ""));
        lines.addAll(output);
        lines.add("    return 0;");
        lines.add("}");
        lines.add("");
        return String.join("\n", lines);
    }

    /**
     * Encodes the trusted expected value outside the untrusted sandbox. The
     * returned protocol exactly matches what the generated harness writes.
     */
    public String expectedOutput(
            ExecutableAssessmentContract contract,
            ExecutableAssessmentContract.TestCase testCase) {
        return encodedValue(
                contract.runtime().signature().returnFixture().id(),
                testCase.expectedOutput());
    }

    private void validateSource(ExecutableAssessmentContract contract, String source) {
        if (source == null || source.isBlank()) {
            throw new IllegalArgumentException("Source code is required");
        }
        if (source.getBytes(StandardCharsets.UTF_8).length > MAX_SOURCE_BYTES) {
            throw new IllegalArgumentException("Submission exceeds the 256 KB source limit");
        }
        if (Pattern.compile("\\bmain\\s*\\(").matcher(source).find()) {
            throw new IllegalArgumentException("Submit only the required function; main is provided by the grader");
        }
        for (String bannedPattern : contract.runtime().bannedApiPatterns()) {
            if (Pattern.compile(bannedPattern).matcher(source).find()) {
                throw new IllegalArgumentException("Submission uses an API forbidden by this assessment contract");
            }
        }
    }

    private String literal(String fixture, JsonNode value) {
        return switch (fixture) {
            case "integer" -> {
                if (!value.isIntegralNumber() || !value.canConvertToInt()) {
                    throw fixtureError(fixture);
                }
                yield Integer.toString(value.intValue());
            }
            case "boolean" -> {
                if (!value.isBoolean()) {
                    throw fixtureError(fixture);
                }
                yield value.booleanValue() ? "true" : "false";
            }
            case "string" -> {
                if (!value.isTextual()) {
                    throw fixtureError(fixture);
                }
                try {
                    yield objectMapper.writeValueAsString(value.textValue());
                } catch (JsonProcessingException exception) {
                    throw fixtureError(fixture);
                }
            }
            case "vector_int" -> {
                if (!value.isArray()) {
                    throw fixtureError(fixture);
                }
                List<String> values = new ArrayList<>();
                for (JsonNode item : value) {
                    if (!item.isIntegralNumber() || !item.canConvertToInt()) {
                        throw fixtureError(fixture);
                    }
                    values.add(Integer.toString(item.intValue()));
                }
                yield "std::vector<int>{" + String.join(", ", values) + "}";
            }
            default -> throw new IllegalArgumentException("Unsupported fixture: " + fixture);
        };
    }

    private String cppType(String fixture) {
        return switch (fixture) {
            case "integer" -> "int";
            case "boolean" -> "bool";
            case "string" -> "std::string";
            case "vector_int" -> "std::vector<int>";
            default -> throw new IllegalArgumentException("Unsupported fixture: " + fixture);
        };
    }

    private List<String> outputLines(String fixture, String value) {
        return switch (fixture) {
            case "integer" -> List.of("    std::cout << \"I:\" << " + value + ";");
            case "boolean" -> List.of(
                    "    std::cout << \"B:\" << (" + value + " ? '1' : '0');");
            case "string" -> List.of(
                    "    std::cout << \"S:\" << " + value + ".size() << ':';",
                    "    std::cout.write(" + value + ".data(), static_cast<std::streamsize>("
                            + value + ".size()));");
            case "vector_int" -> List.of(
                    "    std::cout << \"V:\" << " + value + ".size() << ':';",
                    "    for (std::size_t __lms_i = 0; __lms_i < " + value + ".size(); ++__lms_i) {",
                    "        if (__lms_i != 0) std::cout << ',';",
                    "        std::cout << " + value + "[__lms_i];",
                    "    }");
            default -> throw new IllegalArgumentException("Unsupported fixture: " + fixture);
        };
    }

    private String encodedValue(String fixture, JsonNode value) {
        return switch (fixture) {
            case "integer" -> {
                if (!value.isIntegralNumber() || !value.canConvertToInt()) {
                    throw fixtureError(fixture);
                }
                yield "I:" + value.intValue();
            }
            case "boolean" -> {
                if (!value.isBoolean()) {
                    throw fixtureError(fixture);
                }
                yield value.booleanValue() ? "B:1" : "B:0";
            }
            case "string" -> {
                if (!value.isTextual()) {
                    throw fixtureError(fixture);
                }
                String text = value.textValue();
                yield "S:" + text.getBytes(StandardCharsets.UTF_8).length + ":" + text;
            }
            case "vector_int" -> {
                if (!value.isArray()) {
                    throw fixtureError(fixture);
                }
                List<String> values = new ArrayList<>();
                for (JsonNode item : value) {
                    if (!item.isIntegralNumber() || !item.canConvertToInt()) {
                        throw fixtureError(fixture);
                    }
                    values.add(Integer.toString(item.intValue()));
                }
                yield "V:" + values.size() + ":" + String.join(",", values);
            }
            default -> throw new IllegalArgumentException("Unsupported fixture: " + fixture);
        };
    }

    private IllegalArgumentException fixtureError(String fixture) {
        return new IllegalArgumentException("Invalid value for fixture: " + fixture);
    }
}
