package edu.ai.lms.database;

import lombok.*;
import lombok.experimental.SuperBuilder;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.annotation.ReadOnlyProperty;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.MappedCollection;
import org.springframework.data.relational.core.mapping.Table;

import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;

@Table("chapters")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ChapterJdbcTable {

    // Chapter has composite primary key: (chapter_number, course_id)
    // chapter_number is auto-generated by the database via IDENTITY.
    // We use @Id on chapter_number but handle updates manually via custom queries
    // because Spring Data JDBC's save() doesn't work well with composite keys
    // that have auto-generated parts.

    @Id
    @ReadOnlyProperty
    @Column("chapter_number")
    private Long chapterNumber;

    private String title;
    private String description;

    @Column("course_id")
    private UUID courseId;

    // Chapter-Material M-N relationship via chapter_materials junction table.
    // Spring Data JDBC will use chapter_number as the FK into chapter_materials.
    // The course_id column in chapter_materials must be populated explicitly when
    // building ChapterMaterialJdbcTable instances.
    @MappedCollection(idColumn = "chapter_number")
    @Builder.Default
    private Set<ChapterMaterialJdbcTable> chapterMaterials = new HashSet<>();

    @CreatedDate
    private LocalDateTime createdAt;

    @LastModifiedDate
    private LocalDateTime updatedAt;
}
